"""Writes docs/OUT_OF_SAMPLE.md from the monthly runs (owner, 2026-10-17: one run per setup per month).

PYTHONDONTWRITEBYTECODE=1 .venv/Scripts/python research/2026-10-17-oos/oos_doc.py
Every month is cross-checked: trades.csv net and count against summary.json.
"""

import json
import math
import os
from datetime import datetime, timedelta, timezone

import pandas as pd

OOS, INV = "data/backtests/oos", "data/backtests/inv"
SETUPS = {  # key: (name, out-of-sample prefix, in-sample prefix, config, symbols)
    "v1": ("V1 + room (harmonic)", "v1", "v1cr_room", "config_v1_nocap.yaml", "8 symbols, M15"),
    "f1": ("F1 (breakout fade)", "f1", "setup_breakout_f1", "config_f1_nocap.yaml", "8 symbols, M15"),
    "s1": ("S1 (M1 gold scalp)", "s1", "scalp_s1", "config_scalp_s1.yaml", "XAUUSD, M1"),
}
OOS_MONTHS = [f"2024-{m:02d}" for m in (10, 11, 12)] + [f"2025-{m:02d}" for m in range(1, 10)]
INV_MONTHS = [f"2025-{m:02d}" for m in (10, 11, 12)] + [f"2026-{m:02d}" for m in range(1, 10)]
NOTES_FILE = "research/2026-10-17-oos/notes.md"


def month(root: str, prefix: str, m: str) -> pd.DataFrame | None:
    d = f"{root}/{prefix}_{m}"
    if not os.path.exists(f"{d}/summary.json"):
        return None
    t = pd.read_csv(f"{d}/trades.csv")
    met = json.load(open(f"{d}/summary.json"))["metrics"]
    net = float(t.net.sum()) if len(t) else 0.0
    assert len(t) == met["trades"] and abs(net - met["net_profit"]) < 0.05, (d, len(t), net, met)
    return t


def ci(r: pd.Series) -> str:
    if len(r) < 2:
        return "n/a"
    h = 1.645 * r.std(ddof=1) / math.sqrt(len(r))
    return f"{r.mean() - h:+.3f} .. {r.mean() + h:+.3f}"


def stats(ts: list[pd.DataFrame]) -> dict:
    a = pd.concat(ts) if ts else pd.DataFrame(columns=["r_multiple", "net"])
    r = a.r_multiple.astype(float)
    eq = r.cumsum()
    dd = float((eq.cummax().clip(lower=0) - eq).max()) if len(r) else 0.0
    return {"n": len(r), "mean": r.mean() if len(r) else float("nan"), "sum": r.sum(), "net": a.net.sum(),
            "win": (r > 0).mean() * 100 if len(r) else float("nan"), "ci": ci(r), "dd": dd,
            "pos": sum(1 for t in ts if len(t) and t.r_multiple.mean() > 0)}


def row(m: str, t: pd.DataFrame | None, ref: pd.DataFrame | None) -> str:
    refs = f"{ref.r_multiple.mean():+.3f} ({len(ref)})" if ref is not None and len(ref) else "0 trades"
    if t is None:
        return f"| {m} | | | | | | {refs} |"
    r = t.r_multiple
    if not len(t):
        return f"| {m} | 0 | | | | | {refs} |"
    return (f"| {m} | {len(t)} | {(r > 0).mean() * 100:.0f} | {r.mean():+.3f} | {r.sum():+.2f} | "
            f"{t.net.sum():+,.2f} | {refs} |")


now = datetime.now(timezone.utc) + timedelta(hours=7)
out = [
    "# Out-of-sample year: the active setups on 2024-10 .. 2025-09",
    "",
    "The three setups the bot trades, **unchanged**, on the year before the one they were shaped on (2025-10 ..",
    "2026-09). This year was never used to choose a rule, so it is the first test of whether their edge is real",
    "or fitted. Owner, 2026-10-17: one run per setup per month, each month written here as it finishes.",
    "",
    f"Last update: {now:%Y-%m-%d %H:%M} Thai time. Generated by `research/2026-10-17-oos/oos_doc.py` (do not edit",
    "the tables by hand; notes come from `research/2026-10-17-oos/notes.md`).",
    "",
    "## Setup and method",
    "",
    "| Setup | Config (`data/research/`) | Symbols, entry | In-sample year (2025-10 .. 2026-09) |",
    "|---|---|---|---|",
]
summary = []
tables = []
for key, (name, op, ip, cfg, syms) in SETUPS.items():
    o = [month(OOS, op, m) for m in OOS_MONTHS]
    i = [month(INV, ip, m) for m in INV_MONTHS]
    so, si = stats([t for t in o if t is not None]), stats([t for t in i if t is not None])
    out.append(f"| {name} | `{cfg}` | {syms} | {si['mean']:+.3f} R/trade, {si['n']} trades, max DD {si['dd']:.1f} R |")
    done = sum(t is not None for t in o)
    goal = "-" if not so["n"] else ("✓" if so["mean"] >= 0.15 else "✗")
    summary.append(f"| {name} | {done}/12 | {so['n']} | {so['win']:.0f} | **{so['mean']:+.3f}** | {so['ci']} | "
                   f"{so['pos']}/{done} | {so['dd']:.1f} R | {goal} | {si['mean']:+.3f} ({si['n']}) |"
                   if so["n"] else f"| {name} | {done}/12 | 0 | | | | | | - | {si['mean']:+.3f} ({si['n']}) |")
    tables += [f"### {name}", "",
               "| Month | Trades | Win % | R/trade | Sum R | Net | In-sample same month a year later |",
               "|---|---|---|---|---|---|---|"]
    tables += [row(m, t, ref) for m, t, ref in zip(OOS_MONTHS, o, i)]
    if so["n"]:
        tables.append(f"| **Done** | **{so['n']}** | {so['win']:.0f} | **{so['mean']:+.3f}** | {so['sum']:+.2f} | "
                      f"{so['net']:+,.2f} | year {si['mean']:+.3f} ({si['n']}) |")
    tables.append("")
out += [
    "",
    "- Monthly runs `--start YYYY-MM-01 --end` the next month's first day, outputs `data/backtests/oos/<setup>_YYYY-MM`",
    "  (queue: `research/2026-10-17-oos/oos_queue.sh`); env as the in-sample runs: `ENABLE_HIGH_RISK_PROFILE=false`,",
    "  `MAX_ACCOUNT_DRAWDOWN_PERCENT=50`, consecutive-loss breaker off (50), so no breaker shapes a month.",
    "- V1 and F1 carry the owner's 2026-10-16 change (`max_sl_atr: 20`); their in-sample months ran without it (March",
    "  identical, SETUP_REVIEW §20). S1 is the research config the DEMO lane reproduces trade for trade (§17).",
    "- Data: bars downloaded from the FBS demo terminal on 2026-10-17 (`research/2026-10-17-oos/download_oos.py`):",
    "  H1 of all 29 symbols and M15 of the 8 from 2024-08, D1 from 2022-09, gold M30 from 2024-08 and M1 from",
    "  2024-09. Every month complete; median spreads: gold 20 points (in-sample 23), EURUSD 8-9 (8).",
    "- Judged by R per trade (net mixes lot sizes). Goal ≥ +0.15 R/trade per setup (docs/SETUP_REVIEW.md).",
    "",
    "## Summary",
    "",
    "| Setup | Months done | Trades | Win % | R/trade | 90 % CI | Positive months | Max DD | ≥ +0.15 | In-sample year |",
    "|---|---|---|---|---|---|---|---|---|---|",
    *summary,
    "",
    "## Month by month",
    "",
    *tables,
]
if os.path.exists(NOTES_FILE):
    out += ["## Notes", "", open(NOTES_FILE, encoding="utf-8").read().strip(), ""]
with open("docs/OUT_OF_SAMPLE.md", "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out).rstrip() + "\n")
print("\n".join(summary))
